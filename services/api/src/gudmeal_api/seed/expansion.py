def _hours(open_: str, close: str) -> OpeningHours:
    return OpeningHours(weekly={d: [TimeRange(open=open_, close=close)] for d in range(7)})


def _m(
    rid: str,
    name: str,
    *,
    city: str,
    area: str,
    lat: float,
    lng: float,
    street: str,
    vertical: Vertical = Vertical.FOOD,
    **kw: object,
) -> Restaurant:
    city_name = {"lagos": "Lagos", "enugu": "Enugu"}[city]
    return Restaurant(
        id=rid,
        vertical=vertical,
        city=city,
        name=name,
        slug=rid.split("-", 1)[1],
        area=area,
        location=GeoPoint(lat=lat, lng=lng),
        geohash=geohash_encode(lat, lng, 9),
        address=f"{street}, {area}, {city_name}",
        created_at=datetime(2026, 9, 1, tzinfo=UTC),
        **kw,  # type: ignore[arg-type]
    )


def _i(rid: str, iid: str, cat: str, name: str, price: int, **kw: object) -> MenuItem:
    desc = str(kw.pop("description", ""))
    tags = list(kw.pop("tags", []))  # type: ignore[call-overload]
    return MenuItem(
        id=iid,
        restaurant_id=rid,
        category_id=cat,
        name=name,
        description=desc,
        price_kobo=naira(price),
        tags=tags,
        search_keywords=search_keywords(name, desc, " ".join(tags)),
        **kw,  # type: ignore[arg-type]
    )


def _p(
    rid: str,
    iid: str,
    cat: str,
    name: str,
    price: int,
    unit: str | None,
    desc: str,
    *tags: str,
    pop: int = 50,
) -> MenuItem:
    """A beauty product."""
    return _i(
        rid,
        iid,
        cat,
        name,
        price,
        kind=ItemKind.PRODUCT,
        unit_label=unit,
        description=desc,
        tags=list(tags),
        popularity=pop,
        prep_minutes=10,
    )


def _drinks(rid: str) -> list[MenuItem]:
    rows = [("Chapman", 2000), ("Zobo (50cl)", 1000), ("Chilled water (75cl)", 400), ("Malt drink", 900)]
    return [
        _i(
            rid,
            f"{rid}-drink-{n}",
            "drinks",
            name,
            price,
            kind=ItemKind.DRINK,
            dietary=["vegetarian"],
            description="Chilled",
            popularity=30 - n,
        )
        for n, (name, price) in enumerate(rows)
    ]



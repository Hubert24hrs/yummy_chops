async def seed_expansion(repos: Repositories, now: datetime) -> dict[str, int]:
    menus = _menus()
    counts = {"merchants": 0, "items": 0, "riders": 0, "vouchers": 0}
    for r in MERCHANTS:
        await repos.restaurants.save(r)
        cats, items, groups = menus[r.id]
        await repos.set_menu_categories(r.id, cats)
        for g in groups:
            await repos.option_groups.save(g)
        for pos, it in enumerate(items):
            await repos.items.save(it.model_copy(update={"position": pos}))
        counts["merchants"] += 1
        counts["items"] += len(items)
    for rider in enugu_riders(now):
        await repos.riders.save(rider)
        counts["riders"] += 1
    for v in VOUCHERS:
        await repos.vouchers.save(v)
        counts["vouchers"] += 1
    return counts
